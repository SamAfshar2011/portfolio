const LAYERS = [512, 384, 256, 192, 128, 64, 32];

/** The regression network drawn to scale: width is neuron count. */
export function Taper() {
  const ref = useRef<HTMLOListElement>(null);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el || device.reducedMotion) return;
    const ctx = gsap.context(() => {
      gsap.from('.taper-bar', {
        scaleX: 0,
        duration: 1.2,
        ease: 'settle',
        stagger: 0.07,
        scrollTrigger: { trigger: el, start: 'top 80%', once: true },
      });
    }, el);
    return () => ctx.revert();
  }, []);
  return (
    <ol ref={ref} className="taper" data-reveal aria-label="Network layers from input to output">
      <li className="taper-row taper-in">
        <span className="taper-label t-meta">Input</span>
        <span className="taper-bar" style={{ ['--w' as string]: 23 / 512 }} />
        <span className="taper-n t-num">23</span>
      </li>
      {LAYERS.map((n, i) => (
        <li key={n} className="taper-row">
          <span className="taper-label t-meta">Dense · Swish</span>
          <span className="taper-bar" style={{ ['--w' as string]: n / 512 }} />
          <span className="taper-n t-num">
            {n}
            {i < LAYERS.length - 1 && <span className="taper-extra"> + BatchNorm · Dropout {[0.3, 0.25, 0.2, 0.15, 0.1, 0.05][i]}</span>}
          </span>
        </li>
      ))}
      <li className="taper-row taper-out">
        <span className="taper-label t-meta">Output</span>
        <span className="taper-bar" style={{ ['--w' as string]: 1 / 512 }} />
        <span className="taper-n t-num">1 · sigmoid → probability</span>
      </li>
    </ol>
  );
}

